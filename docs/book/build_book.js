// Builds the PondGate book (Traditional Chinese) from docs/book/*.md.
// Usage: node docs/book/build_book.js
// Output: dist/book-data.js  (window.PondGateBookData: chapters as HTML + a search index)
// The Markdown subset used by the book: # / ## / ### headings, paragraphs, - and 1. lists,
// pipe tables, ![caption](path) figures, ```formula blocks and **bold**.
const fs = require('fs'); const path = require('path');
const DIR = __dirname; const ROOT = path.join(DIR, '..', '..');
const VERSION = '1.3.0';
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const inline = s => esc(s).replace(/\*\*([^*]+)\*\*/g, '<b>$1</b>').replace(/`([^`]+)`/g, '<code>$1</code>');
const plain = s => s.replace(/\*\*|`/g, '');
function convert(md) {
  const L = md.split('\n'); const out = []; let i = 0; let figN = 0;
  const blocks = []; // {level, title, id}
  while (i < L.length) {
    const l = L[i];
    if (!l.trim()) { i++; continue; }
    const h = l.match(/^(#{1,3}) (.*)$/);
    if (h) { blocks.push({ level: h[1].length, title: h[2].trim() }); out.push({ h: h[1].length, t: h[2].trim() }); i++; continue; }
    if (l.startsWith('```')) { const kind = l.slice(3).trim(); const body = []; i++; while (i < L.length && !L[i].startsWith('```')) body.push(L[i++]); i++;
      out.push({ html: kind === 'formula' ? `<div class="bk-eq">${body.map(esc).join('<br>')}</div>` : `<pre>${esc(body.join('\n'))}</pre>`, text: body.join(' ') }); continue; }
    const img = l.match(/^!\[([^\]]*)\]\(([^)]+)\)\s*$/);
    if (img) { out.push({ html: `<figure class="bk-fig"><img data-bk-src="${esc(img[2])}" alt="${esc(img[1])}"><figcaption>${esc(img[1])}</figcaption></figure>`, text: img[1] }); i++; continue; }
    if (l.startsWith('|')) { const rows = []; while (i < L.length && L[i].startsWith('|')) rows.push(L[i++]);
      const cells = r => r.trim().replace(/^\||\|$/g, '').split('|').map(c => c.trim());
      const head = cells(rows[0]); const body = rows.slice(2).map(cells);
      out.push({ html: `<div class="bk-tw"><table class="bk-t"><thead><tr>${head.map(c => `<th>${inline(c)}</th>`).join('')}</tr></thead><tbody>${body.map(r => `<tr>${r.map(c => `<td>${inline(c)}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`, text: [head, ...body].map(r => r.join(' ')).join(' ') }); continue; }
    if (/^(- |\d+\. )/.test(l)) { const ord = /^\d+\. /.test(l); const items = [];
      while (i < L.length && /^(- |\d+\. )/.test(L[i])) items.push(L[i++].replace(/^(- |\d+\. )/, ''));
      out.push({ html: `<${ord ? 'ol' : 'ul'}>${items.map(x => `<li>${inline(x)}</li>`).join('')}</${ord ? 'ol' : 'ul'}>`, text: items.join(' ') }); continue; }
    const para = []; while (i < L.length && L[i].trim() && !/^(#|```|!\[|\||- |\d+\. )/.test(L[i])) para.push(L[i++]);
    out.push({ html: `<p>${inline(para.join(''))}</p>`, text: para.join('') });
  }
  return out;
}
const files = fs.readdirSync(DIR).filter(f => /^\d\d_.*\.md$/.test(f)).sort();
const items = files.flatMap(f => convert(fs.readFileSync(path.join(DIR, f), 'utf8')));
// group: part (#), chapter (##), section (###)
const chapters = []; let part = ''; let ch = null; let sec = null; let n = 0; const index = [];
for (const it of items) {
  if (it.h === 1) { part = /^PondGate/.test(it.t) ? '' : it.t; ch = { id: part ? 'bk-p' + chapters.length : 'bk-front', part, title: part || '序', intro: true, html: part ? `<h2 id="bk-p${chapters.length}">${esc(part)}</h2>` : '', sec: [] }; chapters.push(ch); sec = null; continue; }
  if (it.h === 2) { ch = { id: 'bk-c' + (++n), part, title: it.t, html: '', sec: [] }; chapters.push(ch); sec = { id: ch.id, title: it.t, text: '' }; index.push(sec); ch.html += `<h2 id="${ch.id}">${esc(it.t)}</h2>`; continue; }
  if (it.h === 3) { const id = ch.id + '-s' + (ch.sec.length + 1); sec = { id, title: it.t, chapter: ch.title, text: '' }; ch.sec.push({ id, title: it.t }); index.push(sec); ch.html += `<h3 id="${id}">${esc(it.t)}</h3>`; continue; }
  ch.html += it.html; if (sec) sec.text += ' ' + plain(it.text); else { ch.hasBody = true; index.push(sec = { id: ch.id, title: ch.title, text: plain(it.text) }); }
}
for (let k = chapters.length - 1; k >= 0; k--) if (chapters[k].intro && !chapters[k].hasBody && !chapters[k].sec.length) chapters.splice(k, 1);
index.forEach(s => { if (!s.chapter) s.chapter = s.title; s.text = s.text.replace(/\s+/g, ' ').trim(); });
const data = { version: VERSION, title: 'PondGate 滯洪池演算實務：使用手冊與範例教程', chapters, index,
  downloads: { pdf: `book/PondGate_book_v${VERSION}_zh-Hant.pdf`, zip: `book/PondGate_book_v${VERSION}_examples.zip` } };
const js = `/* Generated by docs/book/build_book.js from docs/book/*.md. Do not edit by hand. */\nwindow.PondGateBookData = ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(ROOT, 'dist', 'book-data.js'), js);
const figs = [...new Set((js.match(/data-bk-src=\\"([^"\\]+)\\"/g) || []).map(m => m.replace(/data-bk-src=\\"|\\"/g, '')))];
const missing = figs.filter(f => !fs.existsSync(path.join(ROOT, 'dist', f)));
console.log('chapters', chapters.length, 'sections', index.length, 'figures', figs.length, 'missing', missing, 'bytes', js.length);
if (missing.length) process.exit(1);
